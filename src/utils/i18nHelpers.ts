export const translateSubCategory = (sub: string | undefined, lang: string, fallbackDefault?: string): string => {
  if (!sub) return fallbackDefault || (lang === 'vi' ? 'Sản Phẩm' : lang === 'zh' ? '产品' : lang === 'ko' ? '제품' : lang === 'ja' ? '製品' : 'Products');
  if (lang === 'zh') return subCategoryZhMap[sub] || sub;
  if (lang === 'ko') return subCategoryKoMap[sub] || sub;
  if (lang === 'ja') return subCategoryJaMap[sub] || sub;
  if (lang === 'vi') return subCategoryViMap[sub] || sub;
  return sub;
};

export const translateFormat = (fmt: string, lang: string): string => {
  if (lang === 'zh') {
    if (formatZhMap[fmt]) return formatZhMap[fmt];
    return fmt
      .replace(/Whole Fruit/g, '整果')
      .replace(/Grade A/g, '特级 Grade A')
      .replace(/Size /g, '规格 ')
      .replace(/Mesh/g, '目')
      .replace(/Fine Powder/g, '细粉')
      .replace(/Puree/g, '果泥')
      .replace(/Juice/g, '果汁')
      .replace(/Concentrate/g, '浓缩汁');
  }
  if (lang === 'ko') {
    if (formatKoMap[fmt]) return formatKoMap[fmt];
    return fmt
      .replace(/Whole Fruit/g, '원물 과일')
      .replace(/Grade A/g, '특급 Grade A')
      .replace(/Size /g, '규격 ')
      .replace(/Mesh/g, '메쉬')
      .replace(/Fine Powder/g, '미세 분말')
      .replace(/Puree/g, '퓨레')
      .replace(/Juice/g, '착즙액')
      .replace(/Concentrate/g, '농축액');
  }
  if (lang === 'ja') {
    if (formatJaMap[fmt]) return formatJaMap[fmt];
    return fmt
      .replace(/Whole Fruit/g, '生果')
      .replace(/Grade A/g, '特級 Grade A')
      .replace(/Size /g, '規格 ')
      .replace(/Mesh/g, 'メッシュ')
      .replace(/Fine Powder/g, '微粉末')
      .replace(/Puree/g, 'ピューレ')
      .replace(/Juice/g, '果汁')
      .replace(/Concentrate/g, '濃縮液');
  }
  return fmt;
};

